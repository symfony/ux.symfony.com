namespace App\EventListener;

use Psr\Cache\CacheItemPoolInterface;
use Symfony\Component\Clock\ClockInterface;
use Symfony\Component\DependencyInjection\Attribute\Autowire;
use Symfony\Component\EventDispatcher\Attribute\AsEventListener;
use Symfony\Component\HttpKernel\Event\RequestEvent;
use Symfony\Component\HttpKernel\KernelEvents;
use Symfony\Component\Lock\LockFactory;
use Symfony\UX\Upload\Event\UploadStartedEvent;

/**
 * Slows down the chunks of the file generated by the Resumable Large Files demo.
 *
 * A server stores 16 small chunks in well under a second: too fast to pause, reload,
 * and resume. Only that generated file is affected, and the demo page says so.
 */
final class SlowDemoUploadListener
{
    public const FILENAME = 'dinosaur-dna-backup.zip';
    public const SLOT = 'upload_demo_slow_chunk_';
    private const DELAY_SECONDS = .7;

    public function __construct(
        #[Autowire(service: 'cache.app')]
        private readonly CacheItemPoolInterface $cache,
        private readonly LockFactory $locks,
        private readonly ClockInterface $clock,
    ) {
    }

    #[AsEventListener(event: UploadStartedEvent::class)]
    public function onUploadStarted(UploadStartedEvent $event): void
    {
        if (self::FILENAME !== $event->getFilename()) {
            return;
        }

        $item = $this->cache->getItem($this->key($event->getUploadId()));
        $this->cache->save($item->set(true)->expiresAfter(3600));
    }

    #[AsEventListener(event: KernelEvents::REQUEST)]
    public function onRequest(RequestEvent $event): void
    {
        $request = $event->getRequest();
        if (!$event->isMainRequest() || 'ux_upload_handle' !== $request->attributes->get('_route') || !$request->isMethod('PUT')) {
            return;
        }

        $uploadId = $request->attributes->get('uploadId');
        if (!\is_string($uploadId) || !$this->cache->hasItem($this->key($uploadId))) {
            return;
        }

        // A waiting chunk holds a PHP worker. Two wait at most, for the whole site:
        // with more visitors on the demo, their chunks are simply not slowed down.
        foreach ([0, 1] as $slot) {
            $lock = $this->locks->createLock(self::SLOT.$slot, 5);
            if ($lock->acquire()) {
                $this->clock->sleep(self::DELAY_SECONDS);
                $lock->release();

                return;
            }
        }
    }

    private function key(string $uploadId): string
    {
        return 'demo_slow_upload_'.hash('xxh128', $uploadId);
    }
}
